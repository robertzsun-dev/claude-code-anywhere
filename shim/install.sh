#!/usr/bin/env bash

# Installation script for Claude Code Remote Access seamless wrapper
# This sets up the claude command to automatically connect to the session server

set -e

echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Claude Code Remote Access - Seamless Wrapper Install    ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
CLAUDE_REMOTE_DIR="$(dirname "$SCRIPT_DIR")"

# Find the real claude binary
echo -e "${CYAN}1. Finding claude binary...${NC}"
CLAUDE_BIN=$(which claude 2>/dev/null || echo "")

if [ -z "$CLAUDE_BIN" ]; then
    echo -e "${RED}✗ Claude binary not found in PATH${NC}"
    echo -e "${YELLOW}  Please install Claude Code first: npm install -g @anthropic-ai/claude-code${NC}"
    exit 1
fi

echo -e "${GREEN}✓ Found claude at: $CLAUDE_BIN${NC}"

# Resolve symlinks to find the real binary
CLAUDE_REAL=$(readlink -f "$CLAUDE_BIN" 2>/dev/null || realpath "$CLAUDE_BIN" 2>/dev/null || echo "$CLAUDE_BIN")
echo -e "${GREEN}✓ Real binary: $CLAUDE_REAL${NC}"

# Check if already installed
if [ -f "${CLAUDE_REAL}-original" ]; then
    echo -e "${YELLOW}! Wrapper already installed (found ${CLAUDE_REAL}-original)${NC}"
    echo -e "${YELLOW}  Run uninstall.sh first if you want to reinstall${NC}"
    exit 0
fi

# Backup the original binary
echo ""
echo -e "${CYAN}2. Backing up original claude binary...${NC}"
CLAUDE_BACKUP="${CLAUDE_REAL}-original"

if [ -w "$CLAUDE_REAL" ]; then
    sudo_cmd=""
else
    echo -e "${YELLOW}  Need sudo to modify $CLAUDE_REAL${NC}"
    sudo_cmd="sudo"
fi

$sudo_cmd mv "$CLAUDE_REAL" "$CLAUDE_BACKUP"
echo -e "${GREEN}✓ Backed up to: $CLAUDE_BACKUP${NC}"

# Install our shim
echo ""
echo -e "${CYAN}3. Installing seamless wrapper...${NC}"

# Create the shim with correct paths
cat > /tmp/claude-shim << EOF
#!/usr/bin/env bash

# Claude Code Interceptor Shim
# Auto-generated by install.sh

# Configuration
CLAUDE_REMOTE_DIR="$CLAUDE_REMOTE_DIR"
CLAUDE_ORIGINAL="$CLAUDE_BACKUP"
SERVER_URL="\${CLAUDE_REMOTE_SERVER:-ws://localhost:8765}"
AUTO_CONNECT="\${CLAUDE_AUTO_CONNECT:-true}"

# Check if server is running (only if auto-connect is enabled)
server_running=false
if [ "\$AUTO_CONNECT" = "true" ]; then
    # Extract host and port from SERVER_URL
    server_addr=\$(echo "\$SERVER_URL" | sed -E 's|^wss?://||' | sed 's|/.*||')
    host=\$(echo "\$server_addr" | cut -d: -f1)
    port=\$(echo "\$server_addr" | cut -d: -f2)

    # Try to connect to server (quick timeout)
    if timeout 0.5 bash -c "cat < /dev/null > /dev/tcp/\$host/\$port 2>/dev/null"; then
        server_running=true
    fi
fi

# If server is running and we have node wrapper, use it
if [ "\$server_running" = "true" ] && [ -f "\$CLAUDE_REMOTE_DIR/wrapper.js" ]; then
    # Run through the wrapper to enable remote access
    export CLAUDE_CMD="\$CLAUDE_ORIGINAL"
    export CLAUDE_REMOTE_SERVER="\$SERVER_URL"
    export CLAUDE_SEAMLESS_MODE=true
    exec node "\$CLAUDE_REMOTE_DIR/wrapper.js" "\$@"
else
    # Server not running or auto-connect disabled, run original claude directly
    exec "\$CLAUDE_ORIGINAL" "\$@"
fi
EOF

# Install the shim
$sudo_cmd mv /tmp/claude-shim "$CLAUDE_REAL"
$sudo_cmd chmod +x "$CLAUDE_REAL"

echo -e "${GREEN}✓ Installed wrapper at: $CLAUDE_REAL${NC}"

# Verify installation
echo ""
echo -e "${CYAN}4. Verifying installation...${NC}"

if [ -f "$CLAUDE_BACKUP" ] && [ -x "$CLAUDE_REAL" ]; then
    echo -e "${GREEN}✓ Installation successful!${NC}"
else
    echo -e "${RED}✗ Installation verification failed${NC}"
    exit 1
fi

# Create config file
echo ""
echo -e "${CYAN}5. Creating configuration...${NC}"

CONFIG_FILE="$HOME/.claude-remote.conf"
if [ ! -f "$CONFIG_FILE" ]; then
    cat > "$CONFIG_FILE" << EOF
# Claude Code Remote Access Configuration
# Source this file in your ~/.bashrc or ~/.zshrc

# Server URL (change this for remote access)
export CLAUDE_REMOTE_SERVER=ws://localhost:8765

# Auto-connect to server (set to false to disable automatic wrapping)
export CLAUDE_AUTO_CONNECT=true

# Claude remote directory
export CLAUDE_REMOTE_DIR=$CLAUDE_REMOTE_DIR
EOF
    echo -e "${GREEN}✓ Created config at: $CONFIG_FILE${NC}"
    echo -e "${YELLOW}  Add this to your ~/.bashrc or ~/.zshrc:${NC}"
    echo -e "${YELLOW}  source $CONFIG_FILE${NC}"
else
    echo -e "${YELLOW}! Config already exists at: $CONFIG_FILE${NC}"
fi

# Install systemd service (optional)
echo ""
echo -e "${CYAN}6. Install systemd service (optional)...${NC}"
echo -e "${YELLOW}Would you like to install the server as a systemd service?${NC}"
echo -e "${YELLOW}This will auto-start the server on boot.${NC}"
echo ""
read -p "Install systemd service? [y/N] " -n 1 -r
echo ""

SYSTEMD_INSTALLED=false

if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo -e "${CYAN}Installing systemd service...${NC}"

    # Check if systemd is available
    if ! command -v systemctl &> /dev/null; then
        echo -e "${RED}✗ systemd not found on this system${NC}"
        echo -e "${YELLOW}  Skipping systemd installation${NC}"
    else
        # Find node path
        NODE_PATH=$(which node)

        # Create service file
        SERVICE_NAME="claude-remote-server.service"
        SERVICE_FILE="/tmp/$SERVICE_NAME"

        cat > "$SERVICE_FILE" << SERVICEEOF
[Unit]
Description=Claude Code Remote Access Server
After=network.target

[Service]
Type=simple
User=$USER
WorkingDirectory=$CLAUDE_REMOTE_DIR
ExecStart=$NODE_PATH $CLAUDE_REMOTE_DIR/server.js
Restart=always
RestartSec=10

# Environment
Environment=NODE_ENV=production
Environment=HOST=0.0.0.0
Environment=PORT=8765

# Logging
StandardOutput=journal
StandardError=journal
SyslogIdentifier=claude-remote-server

[Install]
WantedBy=multi-user.target
SERVICEEOF

        # Install service file
        echo -e "${YELLOW}  Installing service file (may need sudo)...${NC}"
        sudo cp "$SERVICE_FILE" "/etc/systemd/system/$SERVICE_NAME"
        sudo chmod 644 "/etc/systemd/system/$SERVICE_NAME"
        rm "$SERVICE_FILE"

        # Reload systemd
        sudo systemctl daemon-reload
        echo -e "${GREEN}✓ Service file installed${NC}"

        SYSTEMD_INSTALLED=true

        # Ask about enabling and starting
        echo ""
        read -p "Enable service to start on boot? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            sudo systemctl enable "$SERVICE_NAME"
            echo -e "${GREEN}✓ Service enabled for auto-start${NC}"
        fi

        echo ""
        read -p "Start service now? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            sudo systemctl start "$SERVICE_NAME"
            sleep 2

            # Check status
            if systemctl is-active --quiet "$SERVICE_NAME"; then
                echo -e "${GREEN}✓ Service started successfully${NC}"
                echo -e "${GREEN}✓ Server is now running at ws://localhost:8765${NC}"
            else
                echo -e "${YELLOW}! Service may have failed to start${NC}"
                echo -e "${YELLOW}  Check status with: sudo systemctl status $SERVICE_NAME${NC}"
            fi
        fi

        echo ""
        echo -e "${CYAN}Systemd service commands:${NC}"
        echo -e "  Status:  ${YELLOW}sudo systemctl status $SERVICE_NAME${NC}"
        echo -e "  Start:   ${YELLOW}sudo systemctl start $SERVICE_NAME${NC}"
        echo -e "  Stop:    ${YELLOW}sudo systemctl stop $SERVICE_NAME${NC}"
        echo -e "  Restart: ${YELLOW}sudo systemctl restart $SERVICE_NAME${NC}"
        echo -e "  Logs:    ${YELLOW}sudo journalctl -u $SERVICE_NAME -f${NC}"
    fi
else
    echo -e "${YELLOW}Skipped systemd installation${NC}"
    echo -e "${YELLOW}You can start the server manually with: npm run server${NC}"
fi

# Summary
echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Installation Complete!                                   ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo -e "${GREEN}The 'claude' command will now automatically connect to the session server!${NC}"
echo ""
echo -e "${CYAN}Next steps:${NC}"
if [ "$SYSTEMD_INSTALLED" = true ]; then
    echo -e "  1. Server is running as systemd service!"
    echo -e "  2. Use claude normally: ${YELLOW}claude${NC}"
    echo -e "  3. Connect remotely: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run client${NC}"
else
    echo -e "  1. Start the server: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run server${NC}"
    echo -e "  2. Use claude normally: ${YELLOW}claude${NC}"
    echo -e "  3. Connect remotely: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run client${NC}"
fi
echo ""
echo -e "${CYAN}Configuration:${NC}"
echo -e "  Config file: ${YELLOW}$CONFIG_FILE${NC}"
echo -e "  Original claude: ${YELLOW}$CLAUDE_BACKUP${NC}"
echo -e "  Wrapper: ${YELLOW}$CLAUDE_REAL${NC}"
if [ "$SYSTEMD_INSTALLED" = true ]; then
    echo -e "  Systemd service: ${YELLOW}claude-remote-server.service${NC}"
fi
echo ""
echo -e "${CYAN}Behavior:${NC}"
echo -e "  - If server is running → Uses remote access wrapper"
echo -e "  - If server is not running → Uses original claude"
echo -e "  - To disable auto-connect: ${YELLOW}export CLAUDE_AUTO_CONNECT=false${NC}"
echo ""
echo -e "${CYAN}To uninstall:${NC}"
echo -e "  ${YELLOW}cd $CLAUDE_REMOTE_DIR/shim && ./uninstall.sh${NC}"
echo ""
