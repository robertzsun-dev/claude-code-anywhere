#!/usr/bin/env bash

# Installation script for Claude Code API Interceptor
#
# Installs a shim to ~/.claude-shim/bin/claude (prepended to PATH) that
# injects an API interceptor into Claude Code at runtime.
#
# Supports both:
#   - Native installer (Bun standalone ELF binary) → BUN_OPTIONS="--preload ..."
#   - npm install (Node.js) → NODE_OPTIONS="--require ..."
#
# The real claude binary is NEVER modified, so Claude Code upgrades work
# seamlessly — the shim dynamically finds the real binary at runtime.
#
# Benefits:
#   - No terminal rendering issues (no PTY wrapping)
#   - Survives Claude Code upgrades (real binary untouched)
#   - Much less network bandwidth
#   - Structured data (messages, tool calls) instead of raw ANSI
#   - Remote input via stdin injection
#   - Claude Code's local terminal works exactly as designed

set -e

echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Claude Code API Interceptor - Install                    ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# Configuration
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
CLAUDE_REMOTE_DIR="$(dirname "$SCRIPT_DIR")"
INTERCEPT_MODULE="${CLAUDE_REMOTE_DIR}/src/intercept/intercept.cjs"
SHIM_DIR="$HOME/.claude-shim/bin"
SHIM_PATH="${SHIM_DIR}/claude"

# Step 1: Check prerequisites
echo -e "${CYAN}1. Checking prerequisites...${NC}"

# Check Node.js
NODE_VERSION=$(node --version 2>/dev/null || echo "")
if [ -z "$NODE_VERSION" ]; then
    echo -e "${RED}  Node.js not found${NC}"
    exit 1
fi
echo -e "${GREEN}  Node.js: $NODE_VERSION${NC}"

# Check claude (skip our own shim directory when looking)
REAL_CLAUDE=""
while IFS= read -r candidate; do
    if [[ "$candidate" != "${SHIM_DIR}/"* ]]; then
        REAL_CLAUDE="$candidate"
        break
    fi
done < <(which -a claude 2>/dev/null)

if [ -z "$REAL_CLAUDE" ]; then
    echo -e "${RED}  Claude Code not found in PATH${NC}"
    echo -e "${YELLOW}  Install: https://docs.anthropic.com/en/docs/claude-code${NC}"
    exit 1
fi
echo -e "${GREEN}  Claude: $REAL_CLAUDE${NC}"

# Detect native installer (symlink in ~/.local/bin → ~/.local/share/claude/versions/*)
CLAUDE_RESOLVED=$(readlink -f "$REAL_CLAUDE" 2>/dev/null || echo "$REAL_CLAUDE")
if [[ "$CLAUDE_RESOLVED" == *"/.local/share/claude/versions/"* ]]; then
    echo -e "${GREEN}  Detected: Native Claude installer${NC}"
    echo -e "${GREEN}  Binary:   $CLAUDE_RESOLVED${NC}"
elif [[ -L "$REAL_CLAUDE" ]]; then
    echo -e "${GREEN}  Symlink → $CLAUDE_RESOLVED${NC}"
fi

# Check intercept module exists
if [ ! -f "$INTERCEPT_MODULE" ]; then
    echo -e "${RED}  Intercept module not found at: $INTERCEPT_MODULE${NC}"
    exit 1
fi
echo -e "${GREEN}  Intercept module: $INTERCEPT_MODULE${NC}"
echo -e "${GREEN}  Shim directory: $SHIM_DIR${NC}"

# Check if already installed
if [ -f "$SHIM_PATH" ]; then
    echo -e "${YELLOW}  Existing shim found at $SHIM_PATH${NC}"
    echo ""
    read -p "  Replace existing shim? [Y/n] " -n 1 -r
    echo ""
    if [[ $REPLY =~ ^[Nn]$ ]]; then
        echo -e "${YELLOW}  Aborted.${NC}"
        exit 0
    fi
    echo -e "${YELLOW}  Will replace existing shim.${NC}"
fi

# Step 2: Install the intercept shim
echo ""
echo -e "${CYAN}2. Installing intercept shim...${NC}"

# Create shim directory
mkdir -p "$SHIM_DIR"

# Create the shim — it finds the real claude dynamically at runtime
cat > "$SHIM_PATH" << 'SHIMEOF'
#!/usr/bin/env bash

# Claude Code API Interceptor Shim (auto-generated by install.sh)
# Injects API interceptor via --preload into Claude Code's runtime.
#
# The native Claude Code binary is a Bun standalone executable, so we use
# BUN_OPTIONS="--preload ..." (NODE_OPTIONS is ignored by Bun).
# For npm-installed Claude Code (Node.js), we use NODE_OPTIONS="--require ...".
#
# This shim dynamically finds the real claude binary by filtering its own
# directory from PATH. The real binary is never modified, so Claude Code
# upgrades work seamlessly.

SHIM_DIR="@@SHIM_DIR@@"
INTERCEPT_MODULE="@@INTERCEPT_MODULE@@"
AUTO_CONNECT="${CLAUDE_AUTO_CONNECT:-true}"

# Find the real claude by skipping our shim directory
find_real_claude() {
    local new_path
    new_path=$(echo "$PATH" | tr ':' '\n' | grep -Fxv "${SHIM_DIR}" | tr '\n' ':' | sed 's/:$//')
    PATH="$new_path" which claude 2>/dev/null
}

CLAUDE_ORIGINAL=$(find_real_claude)

if [ -z "$CLAUDE_ORIGINAL" ]; then
    echo "Error: Original claude binary not found in PATH" >&2
    echo "PATH (excluding shim): $(echo "$PATH" | tr ':' '\n' | grep -Fxv "${SHIM_DIR}" | tr '\n' ':')" >&2
    exit 1
fi

# Quick bail conditions
if [ "$CLAUDE_INTERCEPT" = "0" ] || [ "$AUTO_CONNECT" != "true" ] || [ ! -f "$INTERCEPT_MODULE" ]; then
    exec "$CLAUDE_ORIGINAL" "$@"
fi

# Check if server is running (< 0.5s timeout)
server_running=false
detected_protocol="ws"
if timeout 0.5 bash -c 'curl -k -s https://localhost:8085/health > /dev/null 2>&1'; then
    server_running=true
    detected_protocol="wss"
elif timeout 0.5 bash -c 'curl -s http://localhost:8085/health > /dev/null 2>&1'; then
    server_running=true
    detected_protocol="ws"
fi

if [ "$server_running" != "true" ]; then
    exec "$CLAUDE_ORIGINAL" "$@"
fi

# Inject interceptor
SERVER_URL="${CLAUDE_REMOTE_SERVER:-${detected_protocol}://localhost:8085}"
export CLAUDE_INTERCEPT_SERVER="${SERVER_URL}"

# Detect runtime: Bun standalone (ELF binary) vs Node.js (script)
CLAUDE_RESOLVED=$(readlink -f "$CLAUDE_ORIGINAL" 2>/dev/null || echo "$CLAUDE_ORIGINAL")
if file "$CLAUDE_RESOLVED" 2>/dev/null | grep -q "ELF\|Mach-O"; then
    # Native binary (Bun standalone) — use BUN_OPTIONS --preload
    export BUN_OPTIONS="--preload ${INTERCEPT_MODULE}${BUN_OPTIONS:+ $BUN_OPTIONS}"
else
    # Script/symlink to script (Node.js) — use NODE_OPTIONS --require
    export NODE_OPTIONS="--require ${INTERCEPT_MODULE}${NODE_OPTIONS:+ $NODE_OPTIONS}"
fi

exec "$CLAUDE_ORIGINAL" "$@"
SHIMEOF

# Replace placeholders with actual paths
sed -i "s|@@SHIM_DIR@@|${SHIM_DIR}|g" "$SHIM_PATH"
sed -i "s|@@INTERCEPT_MODULE@@|${INTERCEPT_MODULE}|g" "$SHIM_PATH"

chmod +x "$SHIM_PATH"
echo -e "${GREEN}  Installed: $SHIM_PATH${NC}"

# Step 3: Verify
echo ""
echo -e "${CYAN}3. Verifying installation...${NC}"

# Check if shim dir is already in PATH
if echo "$PATH" | tr ':' '\n' | grep -Fxq "${SHIM_DIR}"; then
    echo -e "${GREEN}  $SHIM_DIR already in PATH${NC}"

    WHICH_CLAUDE=$(which claude)
    if [ "$WHICH_CLAUDE" = "$SHIM_PATH" ]; then
        echo -e "${GREEN}  'which claude' → $SHIM_PATH (shim)${NC}"
    else
        echo -e "${YELLOW}  'which claude' → $WHICH_CLAUDE${NC}"
        echo -e "${YELLOW}  Expected: $SHIM_PATH${NC}"
        echo -e "${YELLOW}  Make sure $SHIM_DIR is FIRST in PATH${NC}"
    fi
else
    echo -e "${YELLOW}  $SHIM_DIR not yet in PATH (will be added in shell config)${NC}"
fi

# Verify the shim can find the real claude
FOUND_REAL=$(PATH="${SHIM_DIR}:$PATH" bash "$SHIM_PATH" --version 2>/dev/null | head -1 || echo "")
if [ -n "$FOUND_REAL" ]; then
    echo -e "${GREEN}  Shim → real claude: $FOUND_REAL${NC}"
else
    echo -e "${YELLOW}  Could not verify shim → real claude chain${NC}"
fi

# Step 4: Config file
echo ""
echo -e "${CYAN}4. Configuration...${NC}"

CONFIG_FILE="$HOME/.claude-remote.conf"
if [ ! -f "$CONFIG_FILE" ]; then
    cat > "$CONFIG_FILE" << EOF
# Claude Code Remote Access Configuration
export PATH="${SHIM_DIR}:\$PATH"
export CLAUDE_AUTO_CONNECT=true
export CLAUDE_REMOTE_DIR=$CLAUDE_REMOTE_DIR
# export CLAUDE_INTERCEPT_DEBUG=1  # Uncomment to debug interceptor
EOF
    echo -e "${GREEN}  Created: $CONFIG_FILE${NC}"
else
    # Update existing config to use new shim directory
    if ! grep -q "$SHIM_DIR" "$CONFIG_FILE" 2>/dev/null; then
        # Replace old PATH line or add new one
        if grep -q 'export PATH=' "$CONFIG_FILE"; then
            sed -i "s|export PATH=.*|export PATH=\"${SHIM_DIR}:\\\$PATH\"|" "$CONFIG_FILE"
            echo -e "${YELLOW}  Updated PATH in: $CONFIG_FILE${NC}"
        else
            sed -i "1a export PATH=\"${SHIM_DIR}:\$PATH\"" "$CONFIG_FILE"
            echo -e "${YELLOW}  Added PATH to: $CONFIG_FILE${NC}"
        fi
    else
        echo -e "${YELLOW}  Config already has shim PATH: $CONFIG_FILE${NC}"
    fi
fi

# Step 5: Shell integration
echo ""
echo -e "${CYAN}5. Shell integration...${NC}"

SHELL_RC=""
case "${SHELL:-}" in
    */zsh) SHELL_RC="$HOME/.zshrc" ;;
    */bash) SHELL_RC="$HOME/.bashrc" ;;
esac

if [ -n "$SHELL_RC" ]; then
    if grep -q "claude-remote.conf" "$SHELL_RC" 2>/dev/null; then
        echo -e "${YELLOW}  Already configured in $SHELL_RC${NC}"
    else
        read -p "  Add to $SHELL_RC? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            echo "" >> "$SHELL_RC"
            echo "# Claude Code Remote Access" >> "$SHELL_RC"
            echo "[ -f \"$CONFIG_FILE\" ] && source \"$CONFIG_FILE\"" >> "$SHELL_RC"
            echo -e "${GREEN}  Added to $SHELL_RC${NC}"
        fi
    fi
fi

# Clean up legacy shims from previous install approach
echo ""
echo -e "${CYAN}6. Cleaning up legacy installations...${NC}"

LEGACY_CLEANED=false

# Check /usr/local/bin/claude
if [ -f "/usr/local/bin/claude" ] && grep -q "Interceptor Shim\|CLAUDE_INTERCEPT_SERVER" "/usr/local/bin/claude" 2>/dev/null; then
    echo -e "${YELLOW}  Found legacy shim at /usr/local/bin/claude${NC}"
    read -p "  Remove it? [Y/n] " -n 1 -r
    echo ""
    if [[ ! $REPLY =~ ^[Nn]$ ]]; then
        sudo rm -f "/usr/local/bin/claude"
        echo -e "${GREEN}  Removed legacy shim${NC}"
        LEGACY_CLEANED=true
    fi
fi

# Check for claude-original backups from previous approach
for dir in "/usr/local/bin" "$HOME/.local/bin"; do
    if [ -f "${dir}/claude-original" ] || [ -L "${dir}/claude-original" ]; then
        # Verify it's actually a claude binary before doing anything
        local_resolved=$(readlink -f "${dir}/claude-original" 2>/dev/null || echo "${dir}/claude-original")
        is_claude=false
        if file "$local_resolved" 2>/dev/null | grep -q "ELF\|Mach-O"; then
            is_claude=true
        elif head -1 "$local_resolved" 2>/dev/null | grep -q "node\|bun\|javascript"; then
            is_claude=true
        fi

        if [ "$is_claude" = false ]; then
            echo -e "${YELLOW}  Found ${dir}/claude-original but it doesn't look like a claude binary, skipping${NC}"
            continue
        fi

        echo -e "${YELLOW}  Found leftover backup: ${dir}/claude-original${NC}"
        # If the real claude was renamed and is missing, restore it
        if [ ! -f "${dir}/claude" ] && [ ! -L "${dir}/claude" ]; then
            echo -e "${YELLOW}  Restoring ${dir}/claude from backup...${NC}"
            if [[ "$dir" == "$HOME"* ]]; then
                mv "${dir}/claude-original" "${dir}/claude"
            else
                sudo mv "${dir}/claude-original" "${dir}/claude"
            fi
            echo -e "${GREEN}  Restored${NC}"
            LEGACY_CLEANED=true
        else
            read -p "  Remove leftover backup? [Y/n] " -n 1 -r
            echo ""
            if [[ ! $REPLY =~ ^[Nn]$ ]]; then
                if [[ "$dir" == "$HOME"* ]]; then
                    rm -f "${dir}/claude-original"
                else
                    sudo rm -f "${dir}/claude-original"
                fi
                echo -e "${GREEN}  Removed${NC}"
                LEGACY_CLEANED=true
            fi
        fi
    fi
done

if [ "$LEGACY_CLEANED" = false ]; then
    echo -e "${GREEN}  No legacy installations found${NC}"
fi

# Summary
echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Installation Complete!                                   ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo -e "${CYAN}How it works:${NC}"
echo -e "  1. You run ${YELLOW}claude${NC} as usual"
echo -e "  2. Shim at ${YELLOW}$SHIM_PATH${NC} intercepts"
echo -e "  3. Shim finds real claude at ${YELLOW}$REAL_CLAUDE${NC}"
echo -e "  4. API calls are captured and sent to session server"
echo -e "  5. Claude Code upgrades work normally (real binary untouched)"
echo ""
echo -e "${CYAN}Quick start:${NC}"
echo -e "  1. ${YELLOW}source $CONFIG_FILE${NC}  (or open new terminal)"
echo -e "  2. Start server: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run server${NC}"
echo -e "  3. Use claude:   ${YELLOW}claude${NC}"
echo -e "  4. View:         ${YELLOW}http://localhost:8085${NC}"
echo ""
echo -e "${CYAN}To disable: ${YELLOW}export CLAUDE_INTERCEPT=0${NC}"
echo -e "${CYAN}To debug:   ${YELLOW}export CLAUDE_INTERCEPT_DEBUG=1${NC}"
echo -e "${CYAN}To uninstall: ${YELLOW}cd $CLAUDE_REMOTE_DIR/shim && ./uninstall.sh${NC}"
echo ""
