#!/usr/bin/env bash

# Installation script for Claude Code Remote Access seamless wrapper
# This sets up a wrapper in /usr/local/bin to intercept the claude command

set -e

echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Claude Code Remote Access - Seamless Wrapper Install    ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
CLAUDE_REMOTE_DIR="$(dirname "$SCRIPT_DIR")"
WRAPPER_PATH="/usr/local/bin/claude"

# Check if claude is installed
echo -e "${CYAN}1. Checking for claude installation...${NC}"
CLAUDE_BIN=$(which claude 2>/dev/null || echo "")

if [ -z "$CLAUDE_BIN" ]; then
    echo -e "${RED}✗ Claude binary not found in PATH${NC}"
    echo -e "${YELLOW}  Please install Claude Code first: npm install -g @anthropic-ai/claude-code${NC}"
    exit 1
fi

echo -e "${GREEN}✓ Found claude at: $CLAUDE_BIN${NC}"

# Check if wrapper already installed
if [ -f "$WRAPPER_PATH" ]; then
    echo -e "${YELLOW}! Wrapper already installed at $WRAPPER_PATH${NC}"
    echo -e "${YELLOW}  Run uninstall.sh first if you want to reinstall${NC}"
    exit 0
fi

# Install our wrapper
echo ""
echo -e "${CYAN}2. Installing seamless wrapper...${NC}"

# Create the wrapper with correct paths
cat > /tmp/claude-wrapper << 'EOF'
#!/usr/bin/env bash

# Claude Code Remote Access Wrapper
# Auto-generated by install.sh
# This wrapper intercepts 'claude' commands and optionally routes them through the remote access system

# Configuration (replaced by install script)
CLAUDE_REMOTE_DIR="__CLAUDE_REMOTE_DIR__"
AUTO_CONNECT="${CLAUDE_AUTO_CONNECT:-true}"

# Detect if server is running and whether it's using HTTPS
server_running=false
detected_protocol="ws"
if [ "$AUTO_CONNECT" = "true" ]; then
    # Try HTTPS first (wss://)
    if timeout 0.5 bash -c 'curl -k -s https://localhost:8085/health > /dev/null 2>&1'; then
        server_running=true
        detected_protocol="wss"
    # Fall back to HTTP (ws://)
    elif timeout 0.5 bash -c 'curl -s http://localhost:8085/health > /dev/null 2>&1'; then
        server_running=true
        detected_protocol="ws"
    fi
fi

# Use detected protocol or environment variable
SERVER_URL="${CLAUDE_REMOTE_SERVER:-${detected_protocol}://localhost:8085}"

# Find the original claude binary by removing /usr/local/bin from PATH
# and searching for the next 'claude' command
find_original_claude() {
    # Remove /usr/local/bin from PATH to find the next claude
    local new_path=$(echo "$PATH" | tr ':' '\n' | grep -v '^/usr/local/bin$' | tr '\n' ':' | sed 's/:$//')

    # Search for claude in the modified PATH
    local claude_path=$(PATH="$new_path" which claude 2>/dev/null)

    if [ -n "$claude_path" ] && [ -f "$claude_path" ]; then
        echo "$claude_path"
        return 0
    fi

    return 1
}

CLAUDE_ORIGINAL=$(find_original_claude)

if [ -z "$CLAUDE_ORIGINAL" ]; then
    echo "Error: Original claude binary not found in PATH" >&2
    echo "Searched PATH (excluding /usr/local/bin): $(echo "$PATH" | tr ':' '\n' | grep -v '^/usr/local/bin$' | tr '\n' ':')" >&2
    echo "Please ensure Claude Code is installed: npm install -g @anthropic-ai/claude-code" >&2
    exit 1
fi

# If server is running and we have node wrapper, use it
if [ "$server_running" = "true" ] && [ -f "$CLAUDE_REMOTE_DIR/src/wrapper.js" ]; then
    # Run through the wrapper to enable remote access
    export CLAUDE_CMD="$CLAUDE_ORIGINAL"
    export CLAUDE_REMOTE_SERVER="$SERVER_URL"
    export CLAUDE_SEAMLESS_MODE=true
    exec node "$CLAUDE_REMOTE_DIR/src/wrapper.js" "$@"
else
    # Server not running or auto-connect disabled, run original claude directly
    exec "$CLAUDE_ORIGINAL" "$@"
fi
EOF

# Replace placeholders
sed -i "s|__CLAUDE_REMOTE_DIR__|$CLAUDE_REMOTE_DIR|g" /tmp/claude-wrapper

# Install the wrapper to /usr/local/bin (requires sudo)
echo -e "${YELLOW}  Installing wrapper to /usr/local/bin (requires sudo)...${NC}"

if sudo cp /tmp/claude-wrapper "$WRAPPER_PATH" && sudo chmod +x "$WRAPPER_PATH"; then
    echo -e "${GREEN}✓ Installed wrapper at: $WRAPPER_PATH${NC}"
    rm /tmp/claude-wrapper
else
    echo -e "${RED}✗ Failed to install wrapper${NC}"
    rm -f /tmp/claude-wrapper
    exit 1
fi

# Verify installation
echo ""
echo -e "${CYAN}3. Verifying installation...${NC}"

# Check PATH priority
echo -e "${YELLOW}  Checking PATH priority...${NC}"
WHICH_CLAUDE=$(which claude)

if [ "$WHICH_CLAUDE" = "$WRAPPER_PATH" ]; then
    echo -e "${GREEN}✓ Wrapper has correct priority in PATH${NC}"
    echo -e "${GREEN}✓ PATH will find wrapper before original binary${NC}"
else
    echo -e "${YELLOW}! Warning: PATH may not prioritize /usr/local/bin${NC}"
    echo -e "${YELLOW}  which claude returns: $WHICH_CLAUDE${NC}"
    echo -e "${YELLOW}  Expected: $WRAPPER_PATH${NC}"
    echo -e "${YELLOW}  You may need to adjust your PATH to have /usr/local/bin first${NC}"
fi

# Create config file
echo ""
echo -e "${CYAN}4. Creating configuration...${NC}"

CONFIG_FILE="$HOME/.claude-remote.conf"
CONFIG_CREATED=false

if [ ! -f "$CONFIG_FILE" ]; then
    cat > "$CONFIG_FILE" << EOF
# Claude Code Remote Access Configuration
# Auto-sourced by shell rc file

# Ensure /usr/local/bin is first in PATH (for wrapper priority)
export PATH="/usr/local/bin:\$PATH"

# Server URL (change this for remote access)
# Leave commented to enable auto-detection based on cert files (wss:// vs ws://)
# export CLAUDE_REMOTE_SERVER=ws://localhost:8085

# Auto-connect to server (set to false to disable automatic wrapping)
export CLAUDE_AUTO_CONNECT=true

# Claude remote directory
export CLAUDE_REMOTE_DIR=$CLAUDE_REMOTE_DIR
EOF
    echo -e "${GREEN}✓ Created config at: $CONFIG_FILE${NC}"
    CONFIG_CREATED=true
else
    echo -e "${YELLOW}! Config already exists at: $CONFIG_FILE${NC}"
fi

# Auto-add to shell rc file
echo ""
echo -e "${CYAN}5. Configuring shell integration...${NC}"

# Detect shell rc file
SHELL_RC=""
if [ -n "$ZSH_VERSION" ]; then
    SHELL_RC="$HOME/.zshrc"
elif [ -n "$BASH_VERSION" ]; then
    SHELL_RC="$HOME/.bashrc"
else
    # Try to detect from $SHELL
    case "$SHELL" in
        */zsh)
            SHELL_RC="$HOME/.zshrc"
            ;;
        */bash)
            SHELL_RC="$HOME/.bashrc"
            ;;
    esac
fi

if [ -n "$SHELL_RC" ]; then
    # Check if already sourced
    if grep -q "source.*\.claude-remote\.conf" "$SHELL_RC" 2>/dev/null || grep -q "\..*\.claude-remote\.conf" "$SHELL_RC" 2>/dev/null; then
        echo -e "${YELLOW}! Shell rc already sources config${NC}"
    else
        echo ""
        read -p "Add config to $SHELL_RC automatically? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            echo "" >> "$SHELL_RC"
            echo "# Claude Code Remote Access" >> "$SHELL_RC"
            echo "[ -f \"$CONFIG_FILE\" ] && source \"$CONFIG_FILE\"" >> "$SHELL_RC"
            echo -e "${GREEN}✓ Added to $SHELL_RC${NC}"
            echo -e "${YELLOW}  Run: source $SHELL_RC (or restart shell)${NC}"
        else
            echo -e "${YELLOW}Skipped. Manually add to $SHELL_RC:${NC}"
            echo -e "${YELLOW}  source $CONFIG_FILE${NC}"
        fi
    fi
else
    echo -e "${YELLOW}! Could not detect shell rc file${NC}"
    echo -e "${YELLOW}  Manually add to your shell rc file:${NC}"
    echo -e "${YELLOW}  source $CONFIG_FILE${NC}"
fi

# Install systemd service (optional)
echo ""
echo -e "${CYAN}6. Install systemd service (optional)...${NC}"
echo -e "${YELLOW}Would you like to install the server as a systemd service?${NC}"
echo -e "${YELLOW}This will auto-start the server on boot.${NC}"
echo ""
read -p "Install systemd service? [y/N] " -n 1 -r
echo ""

SYSTEMD_INSTALLED=false

if [[ $REPLY =~ ^[Yy]$ ]]; then
    echo -e "${CYAN}Installing systemd service...${NC}"

    # Check if systemd is available
    if ! command -v systemctl &> /dev/null; then
        echo -e "${RED}✗ systemd not found on this system${NC}"
        echo -e "${YELLOW}  Skipping systemd installation${NC}"
    else
        # Find node path
        NODE_PATH=$(which node)

        # Create service file
        SERVICE_NAME="claude-remote-server.service"
        SERVICE_FILE="/tmp/$SERVICE_NAME"

        cat > "$SERVICE_FILE" << SERVICEEOF
[Unit]
Description=Claude Code Remote Access Server
After=network.target

[Service]
Type=simple
User=$USER
WorkingDirectory=$CLAUDE_REMOTE_DIR
ExecStart=$NODE_PATH $CLAUDE_REMOTE_DIR/src/server.js
Restart=always
RestartSec=10

# Environment
Environment=NODE_ENV=production
Environment=HOST=0.0.0.0
Environment=PORT=8085

# Logging
StandardOutput=journal
StandardError=journal
SyslogIdentifier=claude-remote-server

[Install]
WantedBy=multi-user.target
SERVICEEOF

        # Install service file
        echo -e "${YELLOW}  Installing service file (may need sudo)...${NC}"
        sudo cp "$SERVICE_FILE" "/etc/systemd/system/$SERVICE_NAME"
        sudo chmod 644 "/etc/systemd/system/$SERVICE_NAME"
        rm "$SERVICE_FILE"

        # Reload systemd
        sudo systemctl daemon-reload
        echo -e "${GREEN}✓ Service file installed${NC}"

        SYSTEMD_INSTALLED=true

        # Ask about enabling and starting
        echo ""
        read -p "Enable service to start on boot? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            sudo systemctl enable "$SERVICE_NAME"
            echo -e "${GREEN}✓ Service enabled for auto-start${NC}"
        fi

        echo ""
        read -p "Start service now? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            sudo systemctl start "$SERVICE_NAME"
            sleep 2

            # Check status
            if systemctl is-active --quiet "$SERVICE_NAME"; then
                echo -e "${GREEN}✓ Service started successfully${NC}"
                echo -e "${GREEN}✓ Server is now running at ws://localhost:8085${NC}"
            else
                echo -e "${YELLOW}! Service may have failed to start${NC}"
                echo -e "${YELLOW}  Check status with: sudo systemctl status $SERVICE_NAME${NC}"
            fi
        fi

        echo ""
        echo -e "${CYAN}Systemd service commands:${NC}"
        echo -e "  Status:  ${YELLOW}sudo systemctl status $SERVICE_NAME${NC}"
        echo -e "  Start:   ${YELLOW}sudo systemctl start $SERVICE_NAME${NC}"
        echo -e "  Stop:    ${YELLOW}sudo systemctl stop $SERVICE_NAME${NC}"
        echo -e "  Restart: ${YELLOW}sudo systemctl restart $SERVICE_NAME${NC}"
        echo -e "  Logs:    ${YELLOW}sudo journalctl -u $SERVICE_NAME -f${NC}"
    fi
else
    echo -e "${YELLOW}Skipped systemd installation${NC}"
    echo -e "${YELLOW}You can start the server manually with: npm run server${NC}"
fi

# Summary
echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Installation Complete!                                   ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo -e "${GREEN}The 'claude' command will now automatically connect to the session server!${NC}"
echo ""
echo -e "${CYAN}How it works:${NC}"
echo -e "  - Wrapper installed at: ${YELLOW}$WRAPPER_PATH${NC}"
echo -e "  - Wrapper dynamically finds original claude in PATH at runtime"
echo -e "  - PATH priority ensures wrapper is called first"
echo -e "  - Survives npm updates - no hardcoded paths!"
echo ""
echo -e "${CYAN}Next steps:${NC}"
if [ "$SYSTEMD_INSTALLED" = true ]; then
    echo -e "  1. Server is running as systemd service!"
    if [ -n "$SHELL_RC" ] && grep -q "source.*\.claude-remote\.conf" "$SHELL_RC" 2>/dev/null; then
        echo -e "  2. Restart your shell or run: ${YELLOW}source $SHELL_RC${NC}"
        echo -e "  3. Run ${YELLOW}which claude${NC} to verify it shows ${YELLOW}/usr/local/bin/claude${NC}"
    else
        echo -e "  2. Reload shell: ${YELLOW}source $CONFIG_FILE${NC}"
    fi
    echo -e "  4. Use claude normally: ${YELLOW}claude${NC}"
    echo -e "  5. View remotely in browser: ${YELLOW}http://localhost:8085${NC}"
else
    echo -e "  1. Start the server: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run server${NC}"
    if [ -n "$SHELL_RC" ] && grep -q "source.*\.claude-remote\.conf" "$SHELL_RC" 2>/dev/null; then
        echo -e "  2. Restart your shell or run: ${YELLOW}source $SHELL_RC${NC}"
        echo -e "  3. Run ${YELLOW}which claude${NC} to verify it shows ${YELLOW}/usr/local/bin/claude${NC}"
    else
        echo -e "  2. Reload shell: ${YELLOW}source $CONFIG_FILE${NC}"
    fi
    echo -e "  4. Use claude normally: ${YELLOW}claude${NC}"
    echo -e "  5. View remotely in browser: ${YELLOW}http://localhost:8085${NC}"
fi
echo ""
echo -e "${CYAN}Configuration:${NC}"
echo -e "  Config file: ${YELLOW}$CONFIG_FILE${NC}"
echo -e "  Wrapper: ${YELLOW}$WRAPPER_PATH${NC}"
echo -e "  Original claude: ${YELLOW}Dynamically resolved from PATH${NC}"
if [ "$SYSTEMD_INSTALLED" = true ]; then
    echo -e "  Systemd service: ${YELLOW}claude-remote-server.service${NC}"
fi
echo ""
echo -e "${CYAN}Behavior:${NC}"
echo -e "  - If server is running → Uses remote access wrapper"
echo -e "  - If server is not running → Uses original claude"
echo -e "  - To disable auto-connect: ${YELLOW}export CLAUDE_AUTO_CONNECT=false${NC}"
echo ""
echo -e "${CYAN}To uninstall:${NC}"
echo -e "  ${YELLOW}cd $CLAUDE_REMOTE_DIR/shim && sudo ./uninstall.sh${NC}"
echo ""
