#!/usr/bin/env bash

# Installation script for Claude Code API Interceptor
#
# This installs the intercept-mode shim, which uses NODE_OPTIONS to inject
# an API interceptor into Claude Code's Node.js process. Unlike the PTY
# wrapper mode, this captures structured API data instead of terminal output.
#
# Benefits over PTY wrapper mode:
#   - No terminal rendering issues
#   - Survives Claude Code UI upgrades
#   - Much less network bandwidth
#   - Structured data (messages, tool calls) instead of raw ANSI
#   - Claude Code's local terminal works exactly as designed

set -e

echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Claude Code API Interceptor - Install                    ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# Configuration
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
CLAUDE_REMOTE_DIR="$(dirname "$SCRIPT_DIR")"
WRAPPER_PATH="/usr/local/bin/claude"
INTERCEPT_MODULE="${CLAUDE_REMOTE_DIR}/src/intercept/intercept.cjs"

# Step 1: Check prerequisites
echo -e "${CYAN}1. Checking prerequisites...${NC}"

# Check Node.js
NODE_VERSION=$(node --version 2>/dev/null || echo "")
if [ -z "$NODE_VERSION" ]; then
    echo -e "${RED}  Node.js not found${NC}"
    exit 1
fi
echo -e "${GREEN}  Node.js: $NODE_VERSION${NC}"

# Check claude
CLAUDE_BIN=$(which claude 2>/dev/null || echo "")
if [ -z "$CLAUDE_BIN" ]; then
    echo -e "${RED}  Claude Code not found in PATH${NC}"
    echo -e "${YELLOW}  Install: npm install -g @anthropic-ai/claude-code${NC}"
    exit 1
fi
echo -e "${GREEN}  Claude: $CLAUDE_BIN${NC}"

# Check intercept module exists
if [ ! -f "$INTERCEPT_MODULE" ]; then
    echo -e "${RED}  Intercept module not found at: $INTERCEPT_MODULE${NC}"
    exit 1
fi
echo -e "${GREEN}  Intercept module: $INTERCEPT_MODULE${NC}"

# Check if wrapper already installed
if [ -f "$WRAPPER_PATH" ]; then
    echo -e "${YELLOW}  Existing wrapper found at $WRAPPER_PATH${NC}"
    echo ""
    read -p "  Replace with intercept mode? [Y/n] " -n 1 -r
    echo ""
    if [[ $REPLY =~ ^[Nn]$ ]]; then
        echo -e "${YELLOW}  Aborted.${NC}"
        exit 0
    fi
    echo -e "${YELLOW}  Will replace existing wrapper.${NC}"
fi

# Step 2: Install the intercept shim
echo ""
echo -e "${CYAN}2. Installing intercept shim...${NC}"

# Create the shim with correct paths embedded
cat > /tmp/claude-intercept-wrapper << SHIMEOF
#!/usr/bin/env bash

# Claude Code API Interceptor Shim (auto-generated by install-intercept.sh)
# Injects API interceptor into Claude Code via NODE_OPTIONS

CLAUDE_REMOTE_DIR="${CLAUDE_REMOTE_DIR}"
AUTO_CONNECT="\${CLAUDE_AUTO_CONNECT:-true}"
INTERCEPT_MODULE="${INTERCEPT_MODULE}"

# Find original claude (skip /usr/local/bin to avoid recursion)
find_original_claude() {
    local new_path
    new_path=\$(echo "\$PATH" | tr ':' '\\n' | grep -v '^/usr/local/bin\$' | tr '\\n' ':' | sed 's/:\$//')
    PATH="\$new_path" which claude 2>/dev/null
}

CLAUDE_ORIGINAL=\$(find_original_claude)

if [ -z "\$CLAUDE_ORIGINAL" ]; then
    echo "Error: Original claude binary not found" >&2
    exit 1
fi

# Quick bail conditions
if [ "\$CLAUDE_INTERCEPT" = "0" ] || [ "\$AUTO_CONNECT" != "true" ] || [ ! -f "\$INTERCEPT_MODULE" ]; then
    exec "\$CLAUDE_ORIGINAL" "\$@"
fi

# Check if server is running (< 0.5s timeout)
server_running=false
detected_protocol="ws"
if timeout 0.5 bash -c 'curl -k -s https://localhost:8085/health > /dev/null 2>&1'; then
    server_running=true
    detected_protocol="wss"
elif timeout 0.5 bash -c 'curl -s http://localhost:8085/health > /dev/null 2>&1'; then
    server_running=true
    detected_protocol="ws"
fi

if [ "\$server_running" != "true" ]; then
    exec "\$CLAUDE_ORIGINAL" "\$@"
fi

# Inject interceptor via NODE_OPTIONS
SERVER_URL="\${CLAUDE_REMOTE_SERVER:-\${detected_protocol}://localhost:8085}"
export NODE_OPTIONS="\${NODE_OPTIONS:-} --require \${INTERCEPT_MODULE}"
export CLAUDE_INTERCEPT_SERVER="\${SERVER_URL}"

exec "\$CLAUDE_ORIGINAL" "\$@"
SHIMEOF

echo -e "${YELLOW}  Installing to $WRAPPER_PATH (may need sudo)...${NC}"
if sudo cp /tmp/claude-intercept-wrapper "$WRAPPER_PATH" && sudo chmod +x "$WRAPPER_PATH"; then
    echo -e "${GREEN}  Installed: $WRAPPER_PATH${NC}"
    rm /tmp/claude-intercept-wrapper
else
    echo -e "${RED}  Failed to install${NC}"
    rm -f /tmp/claude-intercept-wrapper
    exit 1
fi

# Step 3: Verify
echo ""
echo -e "${CYAN}3. Verifying installation...${NC}"

WHICH_CLAUDE=$(which claude)
if [ "$WHICH_CLAUDE" = "$WRAPPER_PATH" ]; then
    echo -e "${GREEN}  PATH priority correct: $WRAPPER_PATH${NC}"
else
    echo -e "${YELLOW}  Warning: 'which claude' returns $WHICH_CLAUDE${NC}"
    echo -e "${YELLOW}  Expected: $WRAPPER_PATH${NC}"
    echo -e "${YELLOW}  Ensure /usr/local/bin is first in PATH${NC}"
fi

# Step 4: Config file
echo ""
echo -e "${CYAN}4. Configuration...${NC}"

CONFIG_FILE="$HOME/.claude-remote.conf"
if [ ! -f "$CONFIG_FILE" ]; then
    cat > "$CONFIG_FILE" << EOF
# Claude Code Remote Access Configuration
export PATH="/usr/local/bin:\$PATH"
export CLAUDE_AUTO_CONNECT=true
export CLAUDE_REMOTE_DIR=$CLAUDE_REMOTE_DIR
# export CLAUDE_INTERCEPT_DEBUG=1  # Uncomment to debug interceptor
EOF
    echo -e "${GREEN}  Created: $CONFIG_FILE${NC}"
else
    echo -e "${YELLOW}  Config exists: $CONFIG_FILE${NC}"
fi

# Step 5: Shell integration
echo ""
echo -e "${CYAN}5. Shell integration...${NC}"

SHELL_RC=""
case "${SHELL:-}" in
    */zsh) SHELL_RC="$HOME/.zshrc" ;;
    */bash) SHELL_RC="$HOME/.bashrc" ;;
esac

if [ -n "$SHELL_RC" ]; then
    if grep -q "claude-remote.conf" "$SHELL_RC" 2>/dev/null; then
        echo -e "${YELLOW}  Already configured in $SHELL_RC${NC}"
    else
        read -p "  Add to $SHELL_RC? [Y/n] " -n 1 -r
        echo ""
        if [[ ! $REPLY =~ ^[Nn]$ ]]; then
            echo "" >> "$SHELL_RC"
            echo "# Claude Code Remote Access" >> "$SHELL_RC"
            echo "[ -f \"$CONFIG_FILE\" ] && source \"$CONFIG_FILE\"" >> "$SHELL_RC"
            echo -e "${GREEN}  Added to $SHELL_RC${NC}"
        fi
    fi
fi

# Summary
echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║   Installation Complete!                                   ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo -e "${CYAN}How it works:${NC}"
echo -e "  1. You run ${YELLOW}claude${NC} as usual"
echo -e "  2. Shim injects API interceptor via NODE_OPTIONS"
echo -e "  3. Claude Code runs normally (no terminal wrapping)"
echo -e "  4. API calls are captured and sent to session server"
echo -e "  5. View structured data at ${YELLOW}http://localhost:8085/intercept${NC}"
echo ""
echo -e "${CYAN}Differences from PTY wrapper mode:${NC}"
echo -e "  ${GREEN}+ No terminal rendering issues${NC}"
echo -e "  ${GREEN}+ Survives Claude Code upgrades${NC}"
echo -e "  ${GREEN}+ Less bandwidth (structured JSON, not ANSI)${NC}"
echo -e "  ${GREEN}+ Native local terminal experience${NC}"
echo -e "  ${YELLOW}- Observe only (no remote input yet)${NC}"
echo -e "  ${YELLOW}- Viewer at /intercept (separate from /index.html)${NC}"
echo ""
echo -e "${CYAN}Quick start:${NC}"
echo -e "  1. Start server: ${YELLOW}cd $CLAUDE_REMOTE_DIR && npm run server${NC}"
echo -e "  2. Use claude:   ${YELLOW}claude${NC}"
echo -e "  3. View:         ${YELLOW}http://localhost:8085/intercept${NC}"
echo ""
echo -e "${CYAN}To disable: ${YELLOW}export CLAUDE_INTERCEPT=0${NC}"
echo -e "${CYAN}To debug:   ${YELLOW}export CLAUDE_INTERCEPT_DEBUG=1${NC}"
echo -e "${CYAN}To uninstall: ${YELLOW}sudo rm $WRAPPER_PATH${NC}"
echo ""
